// Offline consistency checks: the plugin's copies of a fact must agree with the fact's owner.
//
// Run:  node --test plugins/kattakath-workspace/tests/consistency.test.js
//
//   (a) every <app>_<tool> named in the skills, references, locator open map and RULES is on
//       the generated allowlist (or is one of the portal's own portal_* tools);
//   (b) every allowlisted tool is routed somewhere (the router or references/*.md);
//   (c) every allowlisted write is either guarded (RULES) or exempt with a reason
//       (EXEMPT_WRITES): recorded annotations first, a verb heuristic only without one;
//   (d) the guard matcher in hooks.json is exactly the RULES tools, and no read tool;
//   (e) the router's confirm table is RULES: same IDs, same tools, each row quotes `summary`;
//   (f) every allowlisted app is named in both the plugin.json and router descriptions;
//   (g) the router description is <= 700 chars and its frontmatter is spec-only.

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), "utf8");
const { RULES, EXEMPT_WRITES, GUARDED } = require(path.join(ROOT, "scripts", "write-guard.js"));
const { OPEN_BY_MIME, openFor } = require(path.join(ROOT, "scripts", "corpus-locator.js"));

const allowlist = JSON.parse(read("skills", "kattakath-workspace", "references", "allowlist.json"));
const APPS = allowlist.apps;
const ALLOWED = new Set(Object.entries(APPS).flatMap(([app, tools]) => tools.map((t) => `${app}_${t}`)));
// The portal's own tools: not upstream apps, so not on the allowlist.
const PORTAL = new Set(["portal_list_servers", "portal_toggle_servers", "portal_toggle_single_server"]);

const ROUTER = read("skills", "kattakath-workspace", "SKILL.md");
const REFS_DIR = path.join(ROOT, "skills", "kattakath-workspace", "references");
const REFS = fs.readdirSync(REFS_DIR).filter((f) => f.endsWith(".md")).map((f) => fs.readFileSync(path.join(REFS_DIR, f), "utf8"));
const USER_SKILLS = ["where", "status"].map((s) => read("skills", s, "SKILL.md"));

// Backticked tokens whose prefix is a known app (or portal).
function toolTokens(text) {
  const prefixes = new Set([...Object.keys(APPS), "portal"]);
  const out = new Set();
  for (const m of text.matchAll(/`([a-z]+)_([a-z_]+)`/g)) if (prefixes.has(m[1])) out.add(`${m[1]}_${m[2]}`);
  return out;
}

test("allowlist.json is marked GENERATED and has apps", () => {
  assert.match(allowlist.$comment, /^GENERATED by .*gen-allowlist\.sh/);
  assert.ok(Object.keys(APPS).length >= 14);
});

test("(a) every tool named in skills, references, open map and RULES exists", () => {
  const named = new Set([
    ...toolTokens(ROUTER),
    ...REFS.flatMap((r) => [...toolTokens(r)]),
    ...USER_SKILLS.flatMap((s) => [...toolTokens(s)]),
    ...Object.values(OPEN_BY_MIME).flatMap((o) => [o.tool, o.fallback].filter(Boolean)),
    openFor("x/unknown").tool,
    ...GUARDED,
    ...EXEMPT_WRITES.map((e) => e.tool),
  ]);
  const unknown = [...named].filter((t) => !ALLOWED.has(t) && !PORTAL.has(t));
  assert.deepEqual(unknown, [], `named but not on the allowlist: ${unknown.join(", ")}`);
});

test("(b) every allowlisted tool is routed in the router or a reference", () => {
  const routed = new Set([...toolTokens(ROUTER), ...REFS.flatMap((r) => [...toolTokens(r)])]);
  const unrouted = [...ALLOWED].filter((t) => !routed.has(t));
  assert.deepEqual(unrouted, [], `allowlisted but never routed: ${unrouted.join(", ")}`);
});

// Recorded ToolAnnotations (tests/fixtures/tools-list/<app>.json), where they exist.
const ANNOTATIONS = {};
const TL = path.join(__dirname, "fixtures", "tools-list");
for (const f of fs.readdirSync(TL).filter((x) => x.endsWith(".json"))) {
  const app = f.replace(/\.json$/, "");
  for (const [tool, ann] of Object.entries(JSON.parse(fs.readFileSync(path.join(TL, f), "utf8")).tools)) ANNOTATIONS[`${app}_${tool}`] = ann;
}
const READ_VERBS = /^(get|list|search|read|download|inspect|lookup|compute|resolve|suggest)_/;
function isWrite(tool) {
  const ann = ANNOTATIONS[tool];
  if (ann) return ann.readOnlyHint !== true;
  const verb = tool.slice(tool.indexOf("_") + 1);
  return !READ_VERBS.test(verb);
}

test("(c) tools-list fixtures cover only allowlisted tools, and every app they name is complete", () => {
  for (const t of Object.keys(ANNOTATIONS)) assert.ok(ALLOWED.has(t), `${t} annotated but not allowlisted`);
  for (const f of fs.readdirSync(TL).filter((x) => x.endsWith(".json"))) {
    const app = f.replace(/\.json$/, "");
    assert.deepEqual(Object.keys(JSON.parse(fs.readFileSync(path.join(TL, f), "utf8")).tools).sort(), [...APPS[app]].sort(), `${f} must annotate every ${app} tool`);
  }
});

test("(c) every allowlisted write is guarded or exempt with a reason", () => {
  const covered = new Set([...GUARDED, ...EXEMPT_WRITES.map((e) => e.tool)]);
  const loose = [...ALLOWED].filter((t) => isWrite(t) && !covered.has(t));
  assert.deepEqual(loose, [], `write tools with no rule and no exemption: ${loose.join(", ")}`);
  for (const e of EXEMPT_WRITES) assert.ok(e.reason && e.reason.length > 10, `${e.tool} needs a reason`);
});

test("(c) the heuristic agrees with every recorded annotation (so it is safe where none exists)", () => {
  for (const [tool, ann] of Object.entries(ANNOTATIONS)) {
    const verb = tool.slice(tool.indexOf("_") + 1);
    assert.equal(!READ_VERBS.test(verb), ann.readOnlyHint !== true, `heuristic disagrees on ${tool}`);
  }
});

test("(d) the guard matcher lists exactly the RULES tools, none of them a read", () => {
  const pre = JSON.parse(read("hooks", "hooks.json")).hooks.PreToolUse;
  const entry = pre.find((h) => h.hooks.some((x) => (x.args || []).some((a) => a.endsWith("write-guard.js"))));
  const m = entry.matcher.match(/^\^mcp__\.\+__\(([a-z_|]+)\)\$$/);
  assert.ok(m, `matcher shape changed: ${entry.matcher}`);
  const names = m[1].split("|");
  assert.deepEqual([...names].sort(), [...GUARDED].sort());
  for (const n of names) assert.ok(PORTAL.has(n) || isWrite(n), `${n} is a read tool in the guard matcher`);
  assert.equal(entry.hooks[0].onFailure, "block");
});

test("(e) the router's confirm table is RULES (IDs, tools, summary text)", () => {
  const rows = [...ROUTER.matchAll(/^\| (C\d+) \| (.+?) \| (.+?) \|$/gm)];
  assert.deepEqual(rows.map((r) => r[1]), RULES.map((r) => r.id));
  for (const [i, rule] of RULES.entries()) {
    const [, , text, tools] = rows[i];
    assert.ok(text.includes(rule.summary), `${rule.id}: the row must quote summary ${JSON.stringify(rule.summary)}`);
    assert.deepEqual([...tools.matchAll(/`([a-z_]+)`/g)].map((x) => x[1]), rule.tools, `${rule.id}: Tool(s) column`);
  }
});

// How each app key reads in prose. A derived copy on purpose: triggering needs the words.
const APP_WORDS = {
  gmail: /Gmail/, calendar: /Calendar/, drive: /Drive/, docs: /Docs/, docsread: /Docs/,
  sheets: /Sheets/, slides: /Slides/, chat: /Chat/, tasks: /Tasks/, forms: /Forms/,
  contacts: /Contacts/, people: /People|Contacts/, maps: /Maps/, workspace: /Workspace/,
};

function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n/);
  assert.ok(m, "frontmatter missing");
  const keys = [...m[1].matchAll(/^([A-Za-z][\w-]*):/gm)].map((x) => x[1]);
  const desc = (m[1].match(/^description: "(.*)"$/m) || [])[1];
  return { keys, desc };
}

test("(f) every allowlisted app is named in the plugin.json and router descriptions", () => {
  const pj = JSON.parse(read(".claude-plugin", "plugin.json")).description;
  const { desc } = frontmatter(ROUTER);
  for (const app of Object.keys(APPS)) {
    const re = APP_WORDS[app];
    assert.ok(re, `new app ${app}: add its prose name to APP_WORDS, the plugin.json and router descriptions`);
    assert.match(pj, re, `plugin.json description must name ${app}`);
    assert.match(desc, re, `router description must name ${app}`);
  }
});

test("(g) router description <= 700 chars; frontmatter is name + description only", () => {
  const { keys, desc } = frontmatter(ROUTER);
  assert.deepEqual(keys, ["name", "description"]);
  assert.ok(desc.length <= 700, `description is ${desc.length} chars`);
  assert.ok(Buffer.byteLength(ROUTER) <= 6000, `SKILL.md is ${Buffer.byteLength(ROUTER)} bytes`);
});

test("user-only skills stay user-only", () => {
  for (const s of USER_SKILLS) assert.match(s, /^disable-model-invocation: true$/m);
});

test("plugin.json and the marketplace entry agree on the description", () => {
  const pj = JSON.parse(read(".claude-plugin", "plugin.json"));
  const mk = JSON.parse(fs.readFileSync(path.join(ROOT, "..", "..", ".claude-plugin", "marketplace.json"), "utf8")).plugins.find((p) => p.name === pj.name);
  assert.equal(mk.description, pj.description);
  assert.equal(mk.version, undefined, "the marketplace entry never carries a version");
});
