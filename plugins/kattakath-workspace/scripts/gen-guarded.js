#!/usr/bin/env node
// Write skills/kattakath-workspace/references/guarded.json from write-guard.js's RULES:
// the bare <app>_<tool> names the write guard asks about. nix-config's
// checks.<system>.mcp-portal-posture reads the PINNED copy and fails when the portal
// enables an outward or edit tool this list lacks. tests/consistency.test.js fails when
// the file and RULES (or the hooks.json matcher) drift.
//
//   node scripts/gen-guarded.js           rewrite the file
//   node scripts/gen-guarded.js --check   exit 1 if it has drifted
'use strict';

const fs = require('fs');
const path = require('path');
const { GUARDED } = require('./write-guard.js');

const out = path.join(__dirname, '..', 'skills', 'kattakath-workspace', 'references', 'guarded.json');
const body = `${JSON.stringify({ $comment: 'GENERATED by plugins/kattakath-workspace/scripts/gen-guarded.js from scripts/write-guard.js RULES. Do not edit by hand.', tools: GUARDED }, null, 2)}\n`;

if (process.argv[2] === '--check') {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur === body) console.log('guarded.json up to date');
  else {
    console.error('guarded.json DRIFTED from write-guard.js RULES; rerun without --check');
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${out}`);
}
