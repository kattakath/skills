#!/usr/bin/env bash
# Regenerate skills/kattakath-workspace/references/allowlist.json from its ONE owner,
# kattakath/nix-config's infra/cloudflare/workspace-mcp-apps.nix (plain data, no args).
#
#   scripts/gen-allowlist.sh <nix-config checkout>           rewrite the file
#   scripts/gen-allowlist.sh <nix-config checkout> --check   exit 1 if it has drifted
#
# Two gates watch the copy. skills CI runs this script's --check against nix-config's
# main (a WARNING: the copy may legitimately lead nix-config between the two pushes).
# nix-config's checks.<system>.workspace-plugin-parity compares the same eval with its
# PINNED copy's `apps`, and that one blocks. Needs `nix` and `python3` on PATH.
set -euo pipefail

src=${1:?usage: gen-allowlist.sh <nix-config checkout> [--check]}
mode=${2:-write}
apps="$src/infra/cloudflare/workspace-mcp-apps.nix"
here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/skills/kattakath-workspace/references/allowlist.json"

[ -f "$apps" ] || { echo "gen-allowlist: no $apps" >&2; exit 2; }

note='GENERATED by plugins/kattakath-workspace/scripts/gen-allowlist.sh from kattakath/nix-config infra/cloudflare/workspace-mcp-apps.nix (apps.<app>.tools). Do not edit by hand: change the nix file, then rerun.'
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
nix eval --json --file "$apps" \
  --apply "x: { \"\$comment\" = \"$note\"; apps = builtins.mapAttrs (_: a: a.tools) x.apps; }" \
  | python3 -I -c 'import json,sys; print(json.dumps(json.load(sys.stdin), indent=2))' >"$tmp"

if [ "$mode" = "--check" ]; then
  if cmp -s "$tmp" "$out"; then echo "allowlist.json up to date"; else
    echo "allowlist.json DRIFTED from $apps; rerun without --check" >&2
    diff -u "$out" "$tmp" >&2 || true
    exit 1
  fi
else
  cp "$tmp" "$out"
  echo "wrote $out"
fi
