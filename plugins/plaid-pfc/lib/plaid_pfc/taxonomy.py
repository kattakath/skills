"""The pinned Plaid Personal Finance Category (PFC) taxonomy: load, validate, describe, crosswalk.

The list is a data file (data/pfc-v2.json), generated by `pfc refresh` from Plaid's own CSV.
Nothing here is typed by hand, so the code cannot drift from the pin.
"""
import json
from functools import lru_cache
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent.parent / "data"
REVIEW_MARKER = "NEEDS_REVIEW"   # the consumer's "not yet decided" value; not a Plaid name


@lru_cache(maxsize=None)
def pinned() -> dict:
    return json.loads((DATA / "pfc-v2.json").read_text(encoding="utf-8"))


@lru_cache(maxsize=None)
def crosswalk_table() -> dict:
    return json.loads((DATA / "crosswalk-v1-v2.json").read_text(encoding="utf-8"))


def names() -> list[str]:
    return [d["name"] for d in pinned()["detailed"]]


def primaries() -> list[str]:
    return list(pinned()["primary"])


def by_name() -> dict[str, dict]:
    return {d["name"]: d for d in pinned()["detailed"]}


def is_valid(name: str, allow=(REVIEW_MARKER,)) -> bool:
    return name in by_name() or name in allow


def unknown(values, allow=(REVIEW_MARKER,)) -> list[str]:
    """Distinct values that are neither a pinned detailed name nor allowed, in first-seen order."""
    seen, out = set(), []
    for v in values:
        v = (v or "").strip()
        if v and v not in seen:
            seen.add(v)
            if not is_valid(v, allow):
                out.append(v)
    return out


def primary_of(name: str) -> str | None:
    d = by_name().get(name)
    return d["primary"] if d else None


def crosswalk(v1_name: str) -> dict:
    """{"kind": identical|renamed|split|unknown, "v2": [...]} for a v1 detailed name.
    A split (one v1 name, several v2 names) is never chosen automatically: list it for review."""
    targets = crosswalk_table()["v1_to_v2"].get(v1_name)
    if targets is None:
        return {"kind": "identical" if v1_name in by_name() else "unknown", "v2": [v1_name] if v1_name in by_name() else []}
    if len(targets) > 1:
        return {"kind": "split", "v2": targets}
    return {"kind": "identical" if targets == [v1_name] else "renamed", "v2": targets}
